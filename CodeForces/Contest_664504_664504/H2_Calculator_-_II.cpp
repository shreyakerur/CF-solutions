#include <iostream>
using namespace std;

int main() {
	long long N;
	long long M;
	cin >> N >> M;
	cout << N << " + " << M << " = " << N + M << endl;
	cout << endl;
	cout << N << " - " << M << " = " << N - M << endl;
	cout << endl;
	cout << N << " * " << M << " = " << N * M << endl;
	cout << endl;
	cout << N << " / " << M << " = " << N / M << endl;
	cout << endl;
	cout << N << " % " << M << " = " << N % M << endl;
}
